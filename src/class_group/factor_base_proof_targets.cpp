#include "factor_base_proof_targets_internal.hpp"

#include <cstddef>
#include <vector>

namespace silex::detail {

bool select_factor_base_proof_targets(
        std::vector<slong>& out,
        const PrimeIdealList& decomposition,
        flint::FmpzConstRef rational_prime,
        flint::FmpzConstRef bound) noexcept {
    if (flint::fmpz_sgn(rational_prime) <= 0 ||
        flint::fmpz_sgn(bound) < 0) {
        return false;
    }

    std::vector<slong> selected;
    selected.reserve(static_cast<std::size_t>(decomposition.size()));
    flint::Fmpz norm;
    for (slong i = 0; i < decomposition.size(); ++i) {
        const PrimeIdeal* prime = decomposition.at(i);
        if (prime == nullptr || prime->residue_degree() <= 0) {
            return false;
        }

        flint::fmpz_pow_ui(
                flint::FmpzRef(norm), rational_prime,
                static_cast<ulong>(prime->residue_degree()));
        if (flint::fmpz_cmp(flint::FmpzConstRef(norm), bound) <= 0) {
            selected.push_back(i);
        }
    }

    // The principal (p) relation alone discharges a final e = 1 factor when
    // every other factor is also a proof target: from
    // pO_K = P_1^e_1 ... P_g^e_g with e_g = 1, the class
    // [P_g] = -(e_1 [P_1] + ... + e_{g-1} [P_{g-1}]) lies in the subgroup
    // generated by the other factors.  Without an independently established
    // subgroup witness, retain every selected factor in a norm-truncated
    // decomposition.
    //
    // The rule includes g = 1, an inert prime: the sum above is empty, and
    // indeed the only factor P_1 = pO_K (e = 1, so f = n by
    // sum e_i f_i = n; Cohen, GTM 138, Section 4.8) is principal, so its
    // class is trivial and lies in every subgroup.  A totally ramified
    // singleton (e > 1) stays a target: (p) gives only e [P_1] = 0.
    // Source (2.17.3, the reference cited in
    // docs/reference/algorithms_and_sources.rst): src/basemath/buch2.c
    // be_honest and bnftestprimes skip the last unramified P | p, which
    // leaves nothing to test for an inert p; buch2.c:FBgen keeps inert
    // primes out of the factor base ("a factor base contains only noninert
    // primes"), and buch2.c:bnfisprincipal0 returns the trivial class for
    // an inert prime ideal.
    if (selected.size() == static_cast<std::size_t>(decomposition.size()) &&
        !selected.empty()) {
        const PrimeIdeal* last = decomposition.at(selected.back());
        if (last != nullptr && last->ramification_index() == 1) {
            selected.pop_back();
        }
    }

    out.swap(selected);
    return true;
}

}  // namespace silex::detail
