// Whether a required-prime witness may carry a positive valuation at the
// prime ideal above the rational prime q that the factor base lacks.  Sets
// admissible exactly when q differs from required_rational_prime, the base
// holds at least one prime ideal above q, and exactly one prime ideal above q
// lies outside the base, with ramification index 1.  Then qO_K =
// Q_1^e_1 ... Q_g^e_g with e_g = 1 puts the class of that ideal Q_g in the
// subgroup generated by the base ideals above q, the step
// select_factor_base_proof_targets already uses for the last unramified
// ideal above a rational prime (2.17.3 buch2.c:be_honest and
// bnftestprimes skip it).  When lacking is not null and the ideal is
// admissible, it receives that ideal.  Returns false, with admissible
// false, when the base has no parent order or its order is not maximal, when
// q < 2, when lacking is not null and has a different parent order, when the
// base or the decomposition of q cannot be read, or when lacking cannot be
// set.
bool required_prime_witness_admits_lacking_prime(
        bool& admissible,
        const FactorBase& base,
        flint::FmpzConstRef q,
        flint::FmpzConstRef required_rational_prime,
        PrimeIdeal* lacking = nullptr) noexcept;

// Per-search data for applying the cofactor rejection of
// order_element_factor_over_base_with_required_prime to many candidates of
// one order, factor base and required prime, given by their order-basis
// coordinates, without building an element. Ready only when every
// precondition of the direct path holds, every factor-base rational prime
// block is readable, and the degree is 2 to 4; otherwise callers keep the
// direct path. Scratch members make it single-threaded.
//
// Setup has two parts: required_prime_norm_prefilter_init_base reads the
// order and factor base once, and
// required_prime_norm_prefilter_set_required_prime completes it for one
// required prime, so a scan over many required primes of one base pays the
// base part once. required_prime_norm_prefilter_init does both.
struct RequiredPrimeNormPrefilter {
    bool ready = false;
    // The base part is set for base_source, which must stay unchanged while
    // the prefilter is used.
    bool base_ready = false;
    const FactorBase* base_source = nullptr;
    slong degree = 0;
    // Product of the factor-base rational primes.
    flint::Fmpz base_product;
    // base_product times the required prime's rational prime.
    flint::Fmpz smooth_product;
    // Row i * degree + j holds the order coordinates of w_i * w_j.
    flint::FmpzMat multiplication_table{0, 0};
    flint::FmpzMat multiplication_matrix{0, 0};
    flint::Fmpz norm;
    flint::Fmpz cofactor;
    flint::Fmpz divisor;
    // Degree 2 only: the multiplication table as words, set when every entry
    // has absolute value at most required_prime_norm_prefilter_word_limit.
    bool word_table_ready = false;
    slong word_table[8] = {0, 0, 0, 0, 0, 0, 0, 0};
};

// Largest absolute value of a coordinate or table entry the degree-2 word
// path accepts: 2^31 - 1 on 64-bit words, so each multiplication-matrix entry
// fits a signed word and the determinant fits two words.
inline constexpr slong required_prime_norm_prefilter_word_limit =
        (WORD(1) << (FLINT_BITS / 2 - 1)) - 1;

bool required_prime_norm_prefilter_init(
        RequiredPrimeNormPrefilter& prefilter,
        const FactorBase& base,
        const PrimeIdeal& required_prime) noexcept;

// The required-prime-independent part of required_prime_norm_prefilter_init:
// the order preconditions, base_product and the multiplication table. Sets
// base_ready and clears ready; returns false, with base_ready false, when a
// precondition fails.
bool required_prime_norm_prefilter_init_base(
        RequiredPrimeNormPrefilter& prefilter,
        const FactorBase& base) noexcept;

// Completes a prefilter whose base part was set for this base: the
// required-prime preconditions of the direct path and smooth_product. Sets
// ready exactly when they hold; returns false, with ready false, otherwise.
bool required_prime_norm_prefilter_set_required_prime(
        RequiredPrimeNormPrefilter& prefilter,
        const FactorBase& base,
        const PrimeIdeal& required_prime) noexcept;

// The exact norm of the order element with these coordinates (a 1 x degree
// row), from the multiplication table. Requires a ready prefilter.
bool required_prime_norm_prefilter_norm(
        flint::FmpzRef out,
        RequiredPrimeNormPrefilter& prefilter,
        flint::FmpzMatConstRef coordinates) noexcept;

// Sets rejected exactly when the direct path would reject the element by its
// norm cofactor: the norm is nonzero and not smooth over the primes of
// smooth_product. A false rejection leaves the decision to the direct path.
// Takes the word path below when it applies and the fmpz path otherwise.
bool required_prime_norm_prefilter_rejects(
        bool& rejected,
        RequiredPrimeNormPrefilter& prefilter,
        flint::FmpzMatConstRef coordinates) noexcept;

// The same decision in word arithmetic. Applies only to a ready degree-2
// prefilter with word_table_ready, coordinates of absolute value at most
// required_prime_norm_prefilter_word_limit, and |norm| below 2^FLINT_BITS;
// returns false otherwise, with rejected false, and the caller takes the
// fmpz path.
bool required_prime_norm_prefilter_rejects_word(
        bool& rejected,
        const RequiredPrimeNormPrefilter& prefilter,
        flint::FmpzMatConstRef coordinates) noexcept;

// The same decision with fmpz arithmetic, for every ready prefilter.
bool required_prime_norm_prefilter_rejects_fmpz(
        bool& rejected,
        RequiredPrimeNormPrefilter& prefilter,
        flint::FmpzMatConstRef coordinates) noexcept;

// The cofactor decision of the fmpz path for an element whose exact norm is
// given: rejected exactly when the norm is nonzero and not smooth over the
// primes of smooth_product. Requires a ready prefilter.
bool required_prime_norm_prefilter_rejects_norm(
        bool& rejected,
        RequiredPrimeNormPrefilter& prefilter,
        flint::FmpzConstRef norm) noexcept;

