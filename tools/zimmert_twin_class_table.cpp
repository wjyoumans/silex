// Offline generator for src/factor_base/zimmert_twin_class_table.inc, the
// precomputed constants of Zimmert's twin-class generation bound (H. Zimmert,
// "Ideale kleiner Norm in Idealklassen und eine Regulatorabschaetzung",
// Invent. Math. 62 (1981), 367-380, Korollar 1).
//
// For every signature (r1, r2) with 3 <= n = r1 + 2 r2 <= 20 and a tabulated
// gamma, it encloses c = (F_{a,b}(gamma) + n log pi)/2, a = r1 + r2, b = r2,
// with the library's own Arb evaluation
// (detail::zimmert_twin_class_log_lower_bound), which encloses Zimmert's
// series F_{a,b} (p. 376) by the certified tail bound GB-zimmert-F-tail-bound
// (silex-research, research/proofs/generation/GB-zimmert-F-tail-bound.md at
// commit 06191ff), following the evaluation procedure of that proof file.  It
// encloses
// exp(-c) with arb_exp, takes the upper endpoint U of that ball and writes
// the exact decimal rational E = s / 10^k with s = ceil(U 10^k) and k the
// smallest scale giving s kDigits significant digits.  Every step rounds
// upward, so E >= U >= exp(-c) for the exact c.  No floating point is used.
//
// Regenerate (after changing the evaluation, the gammas or kDigits):
//
//   cmake --build --preset default --target silex-zimmert-twin-class-table
//   build/default/silex-zimmert-twin-class-table
//       > src/factor_base/zimmert_twin_class_table.inc   (one command)
//
// then rebuild and run the silex-generation-bound test, which recomputes
// every entry and checks that it is on the safe side and tight.

#include <silex/flint/arb.hpp>
#include <silex/flint/arf.hpp>
#include <silex/flint/fmpz.hpp>

#include "factor_base/factor_base_internal.hpp"

#include <flint/arb.h>
#include <flint/arf.h>
#include <flint/flint.h>
#include <flint/fmpz.h>

#include <cstdio>

namespace {
namespace sflint = silex::flint;

// Precision of the exp(-c) enclosure and its upper endpoint; must match
// test/t-generation-bound.cpp.
constexpr slong kPrecision = 128;
// Significant decimal digits of each entry: the rounding adds a relative
// error below 10^(1 - kDigits).
constexpr slong kDigits = 30;

// Sets significand and scale so that significand / 10^scale is the
// smallest kDigits-digit decimal at least the upper endpoint of exp(-c).
// Also sets terms and order to the L and K of the tail bound.
bool table_entry(sflint::Fmpz& significand,
                 slong& scale,
                 slong& terms,
                 slong& order,
                 slong r1,
                 slong r2,
                 ulong gamma_hundredths) {
    sflint::Arb c;
    if (!silex::detail::zimmert_twin_class_log_lower_bound(
                sflint::ArbRef(c), r1, r2, gamma_hundredths, &terms,
                &order)) {
        return false;
    }
    sflint::Arb value;
    arb_neg(c.raw(), c.raw());
    arb_exp(value.raw(), c.raw(), kPrecision);
    if (arb_is_finite(value.raw()) == 0 ||
        arb_is_positive(value.raw()) == 0) {
        return false;
    }
    sflint::Arf upper;
    arb_get_ubound_arf(upper.raw(), value.raw(), kPrecision);

    sflint::Fmpz threshold;
    fmpz_ui_pow_ui(threshold.raw(), 10, static_cast<ulong>(kDigits - 1));
    sflint::Arf threshold_arf;
    arf_set_fmpz(threshold_arf.raw(), threshold.raw());
    sflint::Fmpz power;
    sflint::Arf scaled;
    for (slong k = 0; k <= 1000; ++k) {
        fmpz_ui_pow_ui(power.raw(), 10, static_cast<ulong>(k));
        arf_mul_fmpz(scaled.raw(), upper.raw(), power.raw(), ARF_PREC_EXACT,
                     ARF_RND_CEIL);
        if (arf_cmp(scaled.raw(), threshold_arf.raw()) >= 0) {
            arf_get_fmpz(significand.raw(), scaled.raw(), ARF_RND_CEIL);
            scale = k;
            return true;
        }
    }
    return false;
}

}  // namespace

int main() {
    std::printf(
            "// Generated by tools/zimmert_twin_class_table.cpp; do not edit by "
            "hand.\n"
            "// Regenerate by writing the output of the target\n"
            "// silex-zimmert-twin-class-table to this file (see the "
            "generator).\n"
            "//\n"
            "// kZimmertTwinClassTable[n - 3][r2] = {gamma, s, k}: the exact "
            "decimal\n"
            "// rational s / 10^k, s with %ld significant digits, is the upper "
            "endpoint\n"
            "// of the Arb enclosure (%ld bits) of exp(-c), "
            "c = (F_{a,b}(g) + n log pi)/2,\n"
            "// a = r1 + r2, b = r2, from zimmert_twin_class_log_lower_bound "
            "at\n"
            "// g = gamma/100, rounded up.  F_{a,b} is enclosed by "
            "GB-zimmert-F-tail-bound\n"
            "// (silex-research @ 06191ff) with head length L and Taylor "
            "order K.\n"
            "// Zimmert 1981, Korollar 1; test/t-generation-bound.cpp "
            "recomputes every\n"
            "// entry and checks it is safe and tight.\n"
            "constexpr ZimmertTwinClassEntry kZimmertTwinClassTable[18][11] = "
            "{\n",
            static_cast<long>(kDigits), static_cast<long>(kPrecision));
    for (slong degree = 3; degree <= 20; ++degree) {
        std::printf("    {\n        // n = %ld\n", static_cast<long>(degree));
        for (slong r2 = 0; 2 * r2 <= degree; ++r2) {
            const slong r1 = degree - 2 * r2;
            const ulong gamma =
                    silex::detail::zimmert_twin_class_gamma_hundredths(r1, r2);
            if (gamma == 0) {
                std::fprintf(stderr, "no gamma for r1 = %ld, r2 = %ld\n",
                             static_cast<long>(r1), static_cast<long>(r2));
                return 1;
            }
            sflint::Fmpz significand;
            slong scale = 0;
            slong terms = 0;
            slong order = 0;
            if (!table_entry(significand, scale, terms, order, r1, r2,
                             gamma)) {
                std::fprintf(stderr,
                             "evaluation failed for r1 = %ld, r2 = %ld\n",
                             static_cast<long>(r1), static_cast<long>(r2));
                return 1;
            }
            char* digits = fmpz_get_str(nullptr, 10, significand.raw());
            std::printf("        {%lu, \"%s\", %ld},  // r1 = %ld, r2 = %ld"
                        " (L = %ld, K = %ld)\n",
                        static_cast<unsigned long>(gamma), digits,
                        static_cast<long>(scale), static_cast<long>(r1),
                        static_cast<long>(r2), static_cast<long>(terms),
                        static_cast<long>(order));
            flint_free(digits);
        }
        std::printf("    },\n");
    }
    std::printf("};\n");
    return 0;
}
