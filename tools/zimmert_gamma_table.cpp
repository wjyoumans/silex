// Offline generator for src/factor_base/zimmert_gamma_table.inc, the gamma
// parameters of Zimmert's Satz 2 generation bound in degrees 21 to 64
// (H. Zimmert, "Ideale kleiner Norm in Idealklassen und eine
// Regulatorabschaetzung", Invent. Math. 62 (1981), 367-380, Satz 2, p. 372,
// with alpha from Bemerkung 1, p. 373).
//
// For every signature (r1, r2) with 21 <= n = r1 + 2 r2 <= 64 it writes
// detail::zimmert_satz2_gamma_search(r1, r2): the gamma = k/100,
// 1 <= k <= 300, whose Arb enclosure (128 bits) of the right side of Satz 2
// has the largest midpoint, the smallest k on ties.  This is the grid
// maximisation that gives the hand-checked table for n <= 20.  Satz 2 holds
// for every gamma > alpha > 0, so an entry affects only the size of the
// bound, never its validity.  No floating point is used.
//
// Regenerate (after changing the search or the degree range):
//
//   cmake --build --preset default --target silex-zimmert-gamma-table
//   build/default/silex-zimmert-gamma-table
//       > src/factor_base/zimmert_gamma_table.inc   (one command)
//
// then rebuild and run the silex-generation-bound test, which checks every
// entry against the search, and test/zimmert_satz2_oracle.py --gammas 64
// --check src/factor_base/zimmert_gamma_table.inc, which compares the table
// with an independent mpmath maximisation.

#include "factor_base/factor_base_internal.hpp"

#include <flint/flint.h>

#include <cstdio>

namespace {

constexpr slong kFirstDegree = 21;
constexpr slong kLastDegree = 64;
constexpr slong kRowWidth = kLastDegree / 2 + 1;
constexpr slong kEntriesPerLine = 12;

}  // namespace

int main() {
    std::printf(
            "// Generated by tools/zimmert_gamma_table.cpp; do not edit by "
            "hand.\n"
            "// Regenerate by writing the output of the target\n"
            "// silex-zimmert-gamma-table to this file (see the generator).\n"
            "//\n"
            "// kZimmertHighGammaHundredths[n - %ld][r2], %ld <= n <= %ld: "
            "gamma of Zimmert\n"
            "// 1981, Satz 2, in hundredths, from "
            "detail::zimmert_satz2_gamma_search;\n"
            "// 0 marks r2 > n/2.  test/t-generation-bound.cpp checks every "
            "entry.\n"
            "constexpr unsigned char kZimmertHighGammaHundredths[%ld][%ld] = "
            "{\n",
            static_cast<long>(kFirstDegree), static_cast<long>(kFirstDegree),
            static_cast<long>(kLastDegree),
            static_cast<long>(kLastDegree - kFirstDegree + 1),
            static_cast<long>(kRowWidth));
    for (slong degree = kFirstDegree; degree <= kLastDegree; ++degree) {
        std::printf("    {\n        // n = %ld\n        ",
                    static_cast<long>(degree));
        for (slong r2 = 0; 2 * r2 <= degree; ++r2) {
            const slong r1 = degree - 2 * r2;
            const ulong gamma =
                    silex::detail::zimmert_satz2_gamma_search(r1, r2);
            if (gamma == 0 || gamma > 255) {
                std::fprintf(stderr, "no gamma for r1 = %ld, r2 = %ld\n",
                             static_cast<long>(r1), static_cast<long>(r2));
                return 1;
            }
            const bool last = 2 * (r2 + 1) > degree;
            std::printf("%lu,%s", static_cast<unsigned long>(gamma),
                        last ? "\n"
                             : ((r2 + 1) % kEntriesPerLine == 0 ? "\n        "
                                                                : " "));
        }
        std::printf("    },\n");
    }
    std::printf("};\n");
    return 0;
}
